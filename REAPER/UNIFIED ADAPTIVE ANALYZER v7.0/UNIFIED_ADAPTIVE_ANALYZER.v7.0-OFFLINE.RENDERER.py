#!/usr/bin/env python3
# ============================================================
# VOCAL LEVELER — CSV AUDIO PROCESSOR (OFFLINE RENDERER)
# Reads a pre-computed analysis CSV from the v7.0 analyzer,
# maps it to the full-res original WAV, and exports processed audio.
# ============================================================

import os
import time
import numpy as np
import soundfile as sf
from scipy.interpolate import interp1d

# ------------------------------------------------------------
# USER SETTINGS
# ------------------------------------------------------------
# Point to your ORIGINAL, full-resolution audio file (e.g., 96kHz or 192kHz)
WAV_ORIGINAL_PATH = r"X:/AudioProject/Vocal/Stem/_Vocal.STEM_[B].wav"

# Point directly to the CSV generated by VocalLeveler_Analyzer_v7.0.py
CSV_INPUT_PATH    = WAV_ORIGINAL_PATH + "-v7.0-ANALYSIS.csv"

# Output processed WAV path
WAV_OUTPUT_PATH   = WAV_ORIGINAL_PATH.replace(".wav", "-RENDERED-v7.0.wav")

# Global gain scale multiplier (trial & error this without re-analyzing!)
GLOBAL_SCALE      = 1.0  

# Hardcoded analysis rate used by VocalLeveler_Analyzer_v7.0.py (Fast Mode)
ANALYSIS_SR       = 48000  

# ------------------------------------------------------------
# MAIN RENDERER PIPELINE
# ------------------------------------------------------------
def render_audio_from_csv():
    print("==================================================")
    print(" VOCAL LEVELER — CSV AUDIO PROCESSOR")
    print("==================================================")

    if not os.path.exists(WAV_ORIGINAL_PATH):
        print(f"ERROR: Original WAV not found -> {WAV_ORIGINAL_PATH}")
        return
    if not os.path.exists(CSV_INPUT_PATH):
        print(f"ERROR: Analysis CSV not found -> {CSV_INPUT_PATH}")
        print("Please run VocalLeveler_Analyzer_v7.0.py first to generate the CSV.")
        return

    # 1. Load Original Full-Resolution Audio
    print(f"Loading original full-res WAV: {os.path.basename(WAV_ORIGINAL_PATH)}")
    t0 = time.time()
    
    orig_audio, orig_sr = sf.read(WAV_ORIGINAL_PATH)
    is_stereo = orig_audio.ndim > 1
    n_samples_orig = len(orig_audio) if not is_stereo else orig_audio.shape[0]
    duration_s = n_samples_orig / orig_sr

    print(f"  Original SR: {orig_sr} Hz | Duration: {duration_s:.2f}s | Channels: {'Stereo (2)' if is_stereo else 'Mono (1)'}")

    # 2. Parse Pre-computed CSV
    print(f"Parsing analysis CSV: {os.path.basename(CSV_INPUT_PATH)}")
    times = []
    gains_db = []

    with open(CSV_INPUT_PATH, "r", encoding="utf-8") as f:
        lines = f.readlines()
    
    # CSV has 2 header lines (Human header, Machine header). Data starts on line index 2.
    for line in lines[2:]:
        parts = line.strip().split(",")
        if len(parts) >= 10:
            try:
                t_proj = float(parts[0])
                gain_db = float(parts[9]) # Column index 10 is Gain_dB (0-indexed = 9)
                times.append(t_proj)
                times.append(t_proj)
                gains_db.append(gain_db)
            except ValueError:
                continue

    if not times:
        print("ERROR: No valid data found in CSV.")
        return

    print(f"  Loaded {len(times)} control points from CSV.")

    # 3. Upsample Gain Curve to Original Full Sample Rate
    print("Upsampling analysis curve to match original sample rate...")
    orig_times = np.arange(n_samples_orig) / orig_sr

    # Linear interpolation mapping the 10ms CSV frames to every single high-res sample
    interpolator = interp1d(times, gains_db, kind='linear', fill_value="extrapolate")
    sample_gain_db = interpolator(orig_times) * GLOBAL_SCALE
    
    # Convert dB to linear amplitude scale factors
    sample_gain_lin = 10.0 ** (sample_gain_db / 20.0)

    # 4. Apply Gain and Export
    print(f"Applying gain curve and exporting -> {WAV_OUTPUT_PATH}")
    if is_stereo:
        processed_audio = orig_audio * sample_gain_lin[:, np.newaxis]
    else:
        processed_audio = orig_audio * sample_gain_lin

    sf.write(WAV_OUTPUT_PATH, processed_audio, orig_sr, subtype='PCM_24')

    print("==================================================")
    print(" RENDER COMPLETE")
    print(f" Output saved to: {WAV_OUTPUT_PATH}")
    print(f" Time elapsed: {time.time() - t0:.2f} seconds")
    print("==================================================")

if __name__ == "__main__":
    render_audio_from_csv()